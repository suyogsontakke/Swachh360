// Helper to create ISO dates relative to demo reference time so trends always look fresh
function daysAgo(days: number, hoursOffset = 0): string {
  const base = new Date();
  base.setDate(base.getDate() - days);
  base.setHours(9 + hoursOffset, 15, 0, 0);
  return base.toISOString();
}

